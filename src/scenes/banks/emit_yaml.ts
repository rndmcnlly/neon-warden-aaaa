/**
 * Mirrors voiced bank variants (`vo: true`, ids `var_*` and `stat_*`) into
 * `vo/script.yaml`, between the generated-section markers, so agent T's
 * renderer and the subtitle pipeline see them as ordinary lines. The bank
 * files are the source of truth for their text; edit there, then run:
 *
 *   deno run --allow-read --allow-write src/scenes/banks/emit_yaml.ts
 *   deno run --allow-read --allow-write src/i18n/gen_script.ts
 *
 * Variants with other ids (`bark_*`) are existing script lines and are left
 * alone; `tests/banks_test.ts` checks their text still matches.
 */

import { ALL_BANKS } from "./index.ts";

const BEGIN =
  "  # -- banks: voiced variants, GENERATED by src/scenes/banks/emit_yaml.ts";
const END = "  # -- banks: end of generated variants";

export function renderBankYaml(): string {
  const out: string[] = [BEGIN, ""];
  for (const bank of ALL_BANKS) {
    for (const v of bank.variants) {
      if (!v.vo || !/^(var|stat)_/.test(v.id)) continue;
      const route = bank.conditions?.run === "neverFired" ? "pacifist" : "any";
      out.push(
        `  - id: ${v.id}`,
        `    speaker: ${bank.speaker}`,
        `    scene: banks`,
        `    route: ${route}`,
        `    optional: true`,
        `    direction: ${JSON.stringify(v.direction ?? bank.note)}`,
        `    en: ${JSON.stringify(v.en)}`,
        `    es: ${JSON.stringify(v.es)}`,
        `    zh: ${JSON.stringify(v.zh)}`,
        "",
      );
    }
  }
  out.push(END);
  return out.join("\n");
}

/** `yaml` with the generated section replaced (or appended). */
export function spliceBankYaml(yaml: string): string {
  const block = renderBankYaml();
  const start = yaml.indexOf(BEGIN);
  if (start < 0) return `${yaml.trimEnd()}\n\n${block}\n`;
  const end = yaml.indexOf(END, start);
  if (end < 0) throw new Error("vo/script.yaml: bank BEGIN without END");
  return yaml.slice(0, start) + block + yaml.slice(end + END.length);
}

if (import.meta.main) {
  const path = "vo/script.yaml";
  await Deno.writeTextFile(path, spliceBankYaml(await Deno.readTextFile(path)));
  console.log(`${path}: bank variants written`);
}
